#!/bin/bash
# MPH-nx: build the deko3d GPU 3D shaders (variants of GPU3D_Comp.glsl, from
# RSDuck's melonDS Switch port) with uam and embed them as a C source.
#   build_deko_shaders.sh <src/deko/shaders> <outdir>
set -euo pipefail
SRC="$1"; OUT="$2"; DK="${DKRUN:-/home/claude/dk.sh}"
mkdir -p "$OUT/glsl" "$OUT/dksh"
VARIANTS='
InterpXSpansZBuffer InterpSpans;ZBuffer
InterpXSpansWBuffer InterpSpans;WBuffer
BinCombined BinCombined
DepthBlendWBuffer DepthBlend;WBuffer
DepthBlendZBuffer DepthBlend;ZBuffer
RasteriseNoTextureWBuffer Rasterise;WBuffer;NoTexture
RasteriseNoTextureWBufferToon Rasterise;WBuffer;NoTexture;Toon
RasteriseNoTextureWBufferHighlight Rasterise;WBuffer;NoTexture;Highlight
RasteriseUseTextureDecalWBuffer Rasterise;WBuffer;UseTexture;Decal
RasteriseUseTextureModulateWBuffer Rasterise;WBuffer;UseTexture;Modulate
RasteriseUseTextureToonWBuffer Rasterise;WBuffer;UseTexture;Toon
RasteriseUseTextureHighlightWBuffer Rasterise;WBuffer;UseTexture;Highlight
RasteriseShadowMaskWBuffer Rasterise;WBuffer;ShadowMask
RasteriseNoTextureZBuffer Rasterise;ZBuffer;NoTexture
RasteriseNoTextureZBufferToon Rasterise;ZBuffer;NoTexture;Toon
RasteriseNoTextureZBufferHighlight Rasterise;ZBuffer;NoTexture;Highlight
RasteriseUseTextureDecalZBuffer Rasterise;ZBuffer;UseTexture;Decal
RasteriseUseTextureModulateZBuffer Rasterise;ZBuffer;UseTexture;Modulate
RasteriseUseTextureToonZBuffer Rasterise;ZBuffer;UseTexture;Toon
RasteriseUseTextureHighlightZBuffer Rasterise;ZBuffer;UseTexture;Highlight
RasteriseShadowMaskZBuffer Rasterise;ZBuffer;ShadowMask
FinalPass FinalPass
FinalPassEdge FinalPass;EdgeMarking
FinalPassFog FinalPass;Fog
FinalPassEdgeFog FinalPass;EdgeMarking;Fog
FinalPassAA FinalPass;AntiAliasing
FinalPassEdgeAA FinalPass;EdgeMarking;AntiAliasing
FinalPassFogAA FinalPass;Fog;AntiAliasing
FinalPassEdgeFogAA FinalPass;EdgeMarking;Fog;AntiAliasing
ClearCoarseBinMask ClearCoarseBinMask
ClearIndirectWorkCount ClearIndirectWorkCount
CalculateWorkOffsets CalculateWorkOffsets
SortWork SortWork
'
names=()
cmds=""
# MPH-nx resolution scaler: one set per render size. Suffix, then the size
# defines (the 1x set keeps the shader's built-in 256x192).
SETS='
_ 
_S15 ScreenWidth=384;ScreenHeight=288;WorkTileMul=16
_S2 ScreenWidth=512;ScreenHeight=384;WorkTileMul=16
_S3 ScreenWidth=768;ScreenHeight=576;WorkTileMul=14
_S4 ScreenWidth=1024;ScreenHeight=768;WorkTileMul=8
'
while read -r sfx sizes; do
  [ -n "$sfx" ] || continue
  [ "$sfx" = "_" ] && sfx=""
  extra="$VARIANTS"
  [ -n "$sfx" ] && extra="$VARIANTS
Downsample Downsample"
  while read -r base defs; do
    [ -n "$base" ] || continue
    name="$base$sfx"
    python3 - "$SRC/GPU3D_Comp.glsl" "$OUT/glsl/$name.glsl" "$defs" "$sizes" <<'PY'
import sys, re
src, dst, defs, sizes = sys.argv[1], sys.argv[2], set(sys.argv[3].split(';')), sys.argv[4]
out = []
for line in open(src):
    m = re.match(r'\s*#cmakedefine\s+(\w+)', line)
    if m:
        out.append(('#define %s\n' % m.group(1)) if m.group(1) in defs else ('/* #undef %s */\n' % m.group(1)))
    else:
        out.append(line)
    if line.startswith('#version') and sizes:
        for kv in sizes.split(';'):
            k, v = kv.split('=')
            out.append('#define %s %s\n' % (k, v))
open(dst, 'w').write(''.join(out))
PY
    names+=("$name")
    cmds+="uam --stage=comp --out '$OUT/dksh/$name.dksh' '$OUT/glsl/$name.glsl' || exit 1; "
  done <<< "$extra"
done <<< "$SETS"
# presenter: top-screen composite at render size
cp "$SRC/HdCompose.glsl" "$OUT/glsl/HdCompose.glsl"
names+=("HdCompose")
cmds+="uam --stage=comp --out '$OUT/dksh/HdCompose.dksh' '$OUT/glsl/HdCompose.glsl' || exit 1; "
"$DK" "$cmds"
python3 - "$OUT" "${names[@]}" <<'PY'
import sys, os
out, names = sys.argv[1], sys.argv[2:]
with open(os.path.join(out, 'nx_deko_shaders.c'), 'w') as f:
    f.write('/* Generated by build_deko_shaders.sh. */\n')
    for n in names:
        data = open(os.path.join(out, 'dksh', n + '.dksh'), 'rb').read()
        f.write('static const unsigned char s_%s[] __attribute__((aligned(256))) = {' % n)
        f.write(','.join(str(b) for b in data))
        f.write('};\n')
    f.write('typedef struct { const char* name; const unsigned char* data; unsigned size; } NxDekoShaderBlob;\n')
    f.write('const NxDekoShaderBlob g_nx_deko_shaders[] = {\n')
    for n in names:
        size = os.path.getsize(os.path.join(out, 'dksh', n + '.dksh'))
        f.write('  {"%s", s_%s, %d},\n' % (n, n, size))
    f.write('};\nconst unsigned g_nx_deko_shader_count = %d;\n' % len(names))
print('embedded %d shaders' % len(names))
PY

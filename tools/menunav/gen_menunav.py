#!/usr/bin/env python3
"""Generate switch/src/nx_menunav_data.h from Mark's L3 captures.

Usage: gen_menunav.py <captures dir with cap-NNN.bmp> <out header>

Only coarse fingerprints are written (a grid of average colours per button,
cells of at least 4x4 pixels), never the captured pixels themselves.
"""
import sys
from PIL import Image
from spec import SCREENS

capdir, out = sys.argv[1], sys.argv[2]
_cache = {}
def load(c):
    if c not in _cache:
        im = Image.open('%s/cap-%s.bmp' % (capdir, c)).convert('RGB')
        im = im.resize((256, 384), Image.NEAREST).crop((0, 192, 256, 384))
        _cache[c] = im.load()
    return _cache[c]

def grid(rect):
    x0, y0, x1, y1 = rect
    w, h = x1 - x0 + 1, y1 - y0 + 1
    return max(1, min(8, w // 4)), max(1, min(8, h // 4))

def fingerprint(px, rect):
    x0, y0, x1, y1 = rect
    w, h = x1 - x0 + 1, y1 - y0 + 1
    gw, gh = grid(rect)
    out = []
    for j in range(gh):
        for i in range(gw):
            cx0, cx1 = x0 + i * w // gw, x0 + (i + 1) * w // gw
            cy0, cy1 = y0 + j * h // gh, y0 + (j + 1) * h // gh
            s = [0, 0, 0]; n = 0
            for y in range(cy0, cy1):
                for x in range(cx0, cx1):
                    p = px[x, y]
                    s[0] += p[0]; s[1] += p[1]; s[2] += p[2]; n += 1
            out.append(tuple(v // n for v in s))
    return out

KIND = {'nav': 'kNavPort', 'popup': 'kNavPopup', 'game': 'kNavGame', 'starmap': 'kNavStarmap', 'files': 'kNavFiles', 'play': 'kNavPlay'}
fps = []   # flat list of (r,g,b)
def add_fp(px, rect):
    off = len(fps)
    f = fingerprint(px, rect)
    fps.extend(f)
    gw, gh = grid(rect)
    return off, gw, gh

lines_rects = []
lines_screens = []
for s in SCREENS:
    keys = []
    for k in s['keys']:
        off, gw, gh = add_fp(load(s['src']), k)
        keys.append((k, off, gw, gh))
    tg = []
    for t in s['targets']:
        name, rect, need = t[0], t[1], t[2]
        src = t[3] if len(t) > 3 and t[3] else s['src']
        off, gw, gh = add_fp(load(src), rect)
        off2 = add_fp(load(t[4]), rect)[0] if len(t) > 4 else -1
        tg.append((name, rect, need, off, gw, gh, off2))
    first_key = len(lines_rects)
    for (k, off, gw, gh) in keys:
        lines_rects.append('    {%d, %d, %d, %d, %d, %d, %d, false, "key", -1},' % (k[0], k[1], k[2], k[3], off, gw, gh))
    first_t = len(lines_rects)
    names = [t[0] for t in tg]
    for (name, rect, need, off, gw, gh, off2) in tg:
        lines_rects.append('    {%d, %d, %d, %d, %d, %d, %d, %s, "%s", %d},' % (rect[0], rect[1], rect[2], rect[3], off, gw, gh,
                                                                        'true' if need else 'false', name, off2))
    back = names.index(s['back']) if s['back'] in names else -1
    default = names.index(s['default']) if s['default'] in names else -1
    lines_screens.append('    {"%s", %s, %d, %d, %d, %d, %d, %d},' % (
        s['name'], KIND[s['kind']], first_key, len(keys), first_t, len(tg), back, default))

with open(out, 'w') as f:
    f.write('// Generated by tools/menunav/gen_menunav.py from MPH-nx L3 captures.\n')
    f.write('// Coarse colour fingerprints only (average colour per cell of 4x4 or more\n')
    f.write('// pixels); no game graphics. Do not edit by hand.\n#pragma once\n\n')
    f.write('static const uint8_t kNavFp[][3] = {\n')
    for i in range(0, len(fps), 6):
        f.write('    ' + ' '.join('{%d,%d,%d},' % p for p in fps[i:i + 6]) + '\n')
    f.write('};\n\nstatic const NavRect kNavRects[] = {\n' + '\n'.join(lines_rects) + '\n};\n\n')
    f.write('static const NavScreen kNavScreens[] = {\n' + '\n'.join(lines_screens) + '\n};\n')
print('fingerprint cells', len(fps), 'rects', len(lines_rects), 'screens', len(lines_screens))

"""Generate the native C sources for the whole ARM9 program.

Output (never committed: it is derived from the game):
  nr_static_NN.c   static image and ITCM functions
  nr_ovII_NN.c     overlay II functions
  nr_funcs.h       prototypes
  nr_tables.c      entry tables (static, one per overlay) and overlay metadata
"""
import os, sys, hashlib
from analyze import analyze_all
from gen import FuncGen

UNIT_BYTES = 4 * 1024 * 1024


def put(out, name, text, stale):
    path = os.path.join(out, name)
    stale.discard(name)
    if os.path.exists(path) and open(path).read() == text:
        return
    open(path, 'w').write(text)


class Buf:
    """Collects a file's text; writes it only if it differs from what is there."""
    def __init__(self, out, name, stale):
        self.out, self.name, self.stale, self.parts = out, name, stale, []
    def write(self, s): self.parts.append(s)
    def __enter__(self): return self
    def __exit__(self, *a): put(self.out, self.name, ''.join(self.parts), self.stale)


def cname(prefix, f):
    return '%s_%08X_%s' % (prefix, f.entry, 't' if f.thumb else 'a')


def fnv1a64(data):
    # Overlay identity without embedding cartridge bytes (nr_runtime.cpp ov_present).
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main(rom, out):
    os.makedirs(out, exist_ok=True)
    # Files are rewritten only when their content changes, so the build
    # recompiles only units whose code changed; stale ones are removed at the end.
    stale = {f for f in os.listdir(out)
             if f.startswith('nr_') and (f.endswith('.c') or f.endswith('.h'))}
    res = analyze_all(rom, verbose=False)
    static = {k: f for k, f in res['static'].funcs.items() if not f.bad}
    static_names = {k: cname('N', f) for k, f in static.items()}

    units = []          # (filename, [code strings])
    protos = []
    tables = {}         # 'static' or overlay id -> list of (key, name)
    stats = {}

    def emit_group(tag, prefix, funcs, names_local):
        cur, size, n = [], 0, 0
        entries = []
        def resolve(target, thumb):
            k = (target & ~1, bool(thumb))
            if k in names_local: return ('direct', names_local[k])
            if k in static_names: return ('direct', static_names[k])
            return ('dyn', None)
        for k in sorted(funcs):
            f = funcs[k]
            g = FuncGen(f, names_local[k], resolve, set())
            code = g.generate()
            protos.append('void %s(uint32_t entry);' % names_local[k])
            for a in sorted(g.labels | {f.entry}):
                entries.append(((a | (1 if f.thumb else 0)), names_local[k], a == f.entry))
            cur.append(code); size += len(code)
            if size >= UNIT_BYTES:
                units.append(('nr_%s_%02d.c' % (tag, n), cur)); n += 1; cur, size = [], 0
        if cur:
            units.append(('nr_%s_%02d.c' % (tag, n), cur))
        # prefer the function whose own entry is the address
        best = {}
        for key, name, own in entries:
            if key not in best or (own and not best[key][1]):
                best[key] = (name, own)
        tables[tag] = sorted((k, v[0]) for k, v in best.items())
        stats[tag] = (len(funcs), sum(len(f.insns) for f in funcs.values()), len(tables[tag]))

    emit_group('static', 'N', static, static_names)
    ovmeta = []
    for oid, (o, own) in sorted(res['overlays'].items()):
        good = {k: f for k, f in own.items() if not f.bad}
        names = {k: cname('O%02d' % oid, f) for k, f in good.items()}
        emit_group('ov%02d' % oid, 'O%02d' % oid, good, names)
        img = o['image']
        # identity: hash of the first 256 bytes of code plus the length
        sig = hashlib.sha1(img[:256]).hexdigest()[:16]
        ovmeta.append((oid, o['ram'], len(img), sig, img[:256]))

    hdr = ['/* generated by tools/nrecomp/gen_all.py; derived from the game, do not commit */',
           '#pragma once', '#include "nr_runtime.h"'] + protos
    put(out, 'nr_funcs.h', '\n'.join(hdr) + '\n', stale)
    for fname, codes in units:
        with Buf(out, fname, stale) as fh:
            fh.write('/* generated by tools/nrecomp/gen_all.py; do not commit */\n')
            fh.write('#include "nr_funcs.h"\n')
            fh.write('#pragma GCC diagnostic ignored "-Wunused-label"\n')
            fh.write('#pragma GCC diagnostic ignored "-Wunused-variable"\n')
            fh.write('#pragma GCC diagnostic ignored "-Wunused-but-set-variable"\n\n')
            fh.write('\n\n'.join(codes))
            fh.write('\n')
    with Buf(out, 'nr_tables.c', stale) as fh:
        fh.write('/* generated; do not commit */\n#include "nr_funcs.h"\n#include "nr_tables.h"\n\n')
        for tag, rows in tables.items():
            fh.write('const NrEntry nr_tab_%s[] = {\n' % tag)
            for k, name in rows:
                fh.write('  {0x%08Xu, %s},\n' % (k, name))
            fh.write('};\nconst uint32_t nr_tab_%s_count = %d;\n\n' % (tag, len(rows)))
        fh.write('const NrOverlay nr_overlays[] = {\n')
        for oid, ram, size, sig, head in ovmeta:
            tag = 'ov%02d' % oid
            fh.write('  {%d, 0x%08Xu, 0x%Xu, nr_tab_%s, %d, 0x%016XULL},\n' % (
                oid, ram, size, tag, len(tables[tag]), fnv1a64(head[:64])))
        fh.write('};\nconst uint32_t nr_overlay_count = %d;\n' % len(ovmeta))
    for tag, (nf, ni, ne) in stats.items():
        print('%-7s %5d functions %7d instructions %6d entries' % (tag, nf, ni, ne))
    for f in stale:
        os.remove(os.path.join(out, f))
    print('%d source units' % len(units))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
